export const WORD_COUNT = WORDS.length;

export function pickWord(prevKana: string): Word {
  const roll = Math.random();
  const fit = (w: Word) => {
    if (w.kana === prevKana) return false;
    if (roll < 0.58) return w.kana.length <= 4;
    if (roll < 0.9) return w.kana.length <= 7;
    return w.kana.length >= 6;
  };
  const pool = WORDS.filter(fit);
  const list = pool.length > 0 ? pool : WORDS.filter((w) => w.kana !== prevKana);
  return list[Math.floor(Math.random() * list.length)] ?? WORDS[0];
}

